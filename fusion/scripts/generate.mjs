// Generates the two halves of the `react` shim:
//
//   types/react.d.ts  what TypeScript sees when a project imports "react"
//   src/react.ts      what the bundler serves when a project imports "react"
//
// Both re-export everything from real React except the names Fusion redefines
// in src/hooks.ts. They have to be generated because `@types/react` uses
// `export =`, which TypeScript refuses to re-export with `export *`, and
// because React itself is CommonJS, where `export *` is not reliable across
// bundlers.
//
//   node scripts/generate.mjs           write the files
//   node scripts/generate.mjs --check   fail if the files on disk are stale
//                                       (run in CI: catches @types/react drift)

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(resolve(root, "package.json"));

// --- inputs -----------------------------------------------------------------

const typesPkgPath = require.resolve("@types/react/package.json");
const typesPkg = require(typesPkgPath);
const typesSource = readFileSync(resolve(dirname(typesPkgPath), "index.d.ts"), "utf8");
const reactPkg = require("react/package.json");
const runtimeNames = Object.keys(require("react")).sort();

/** Names declared directly inside `declare namespace React { ... }`. */
function namespaceMembers(source) {
  const start = source.indexOf("declare namespace React {");
  const end = source.indexOf("\n}\n", start);
  if (start < 0 || end < 0) throw new Error("Could not find `declare namespace React` in @types/react.");
  const names = new Set();
  // Members sit at exactly one level of indentation; nested declarations are deeper.
  const member =
    /^ {4}(?:export )?(?:declare )?(?:abstract )?(?:type|interface|function|const|let|var|class|enum|namespace) ([A-Za-z_$][\w$]*)/gm;
  for (const [, name] of source.slice(start, end).matchAll(member)) names.add(name);
  return [...names].sort();
}

/** Names Fusion redefines: every `export const` in src/hooks.ts. */
const overrides = [...readFileSync(resolve(root, "src/hooks.ts"), "utf8").matchAll(/^export const (\w+)/gm)]
  .map(([, name]) => name)
  .sort();

/** Names Fusion adds, by source module. `type` entries have no runtime value. */
const additions = [
  { name: "stable", from: "stable", type: false },
  { name: "Stable", from: "stable", type: true },
];

const typeNames = namespaceMembers(typesSource);

// --- sanity checks ----------------------------------------------------------

for (const name of overrides) {
  if (!typeNames.includes(name)) throw new Error(`src/hooks.ts overrides "${name}", which @types/react does not declare.`);
  if (!runtimeNames.includes(name)) throw new Error(`src/hooks.ts overrides "${name}", which react does not export.`);
}
for (const { name } of additions) {
  if (typeNames.includes(name) || runtimeNames.includes(name)) {
    throw new Error(`Fusion adds "${name}", but React now exports that name too.`);
  }
}
const isInternal = (name) => name.startsWith("__");
const untyped = runtimeNames.filter((name) => !isInternal(name) && !typeNames.includes(name));
if (typeNames.length < 200) throw new Error(`Only found ${typeNames.length} names in @types/react; the scanner is probably broken.`);

// --- outputs ----------------------------------------------------------------

const banner = (extra) => `// GENERATED by scripts/generate.mjs. Do not edit; run \`pnpm generate\` instead.
// Source: react@${reactPkg.version}, @types/react@${typesPkg.version}
${extra}`;

const dts = `${banner(`//
// The public type of the Fusion \`react\` shim. It has the same shape as
// @types/react (an \`export =\` namespace, so \`import React from "react"\`,
// \`import * as React from "react"\` and \`import { useEffect } from "react"\` all
// behave as usual), with the names Fusion redefines swapped in.`)}

import Original = require("fusion-react-original");
import * as FusionHooks from "../src/hooks";
import * as FusionStable from "../src/stable";

export = React;

declare namespace React {
  // --- redefined by Fusion ---
${overrides.map((name) => `  export import ${name} = FusionHooks.${name};`).join("\n")}

  // --- added by Fusion ---
${additions.map(({ name }) => `  export import ${name} = FusionStable.${name};`).join("\n")}

  // --- passed through from React ---
${typeNames
  .filter((name) => !overrides.includes(name))
  .map((name) => `  export import ${name} = Original.${name};`)
  .join("\n")}
}
`;

const passThrough = runtimeNames.filter((name) => !overrides.includes(name));
const added = additions.filter(({ type }) => !type);

const runtime = `${banner(`//
// The runtime half of the Fusion \`react\` shim: every export of real React,
// with the names Fusion redefines swapped in. Its public type is
// ../types/react.d.ts, not the types inferred from this file.`)}

import Original from "fusion-react-original";
import * as hooks from "./hooks";
${[...new Set(added.map(({ from }) => from))]
  .map((from) => `import { ${added.filter((a) => a.from === from).map((a) => a.name).join(", ")} } from "./${from}";`)
  .join("\n")}

// React is CommonJS and exports some names that @types/react does not declare.
const React: Record<string, any> = Original;

// --- redefined by Fusion ---
export { ${overrides.join(", ")} } from "./hooks";

// --- added by Fusion ---
export { ${added.map(({ name }) => name).join(", ")} };

// --- passed through from React ---
${passThrough.map((name) => `export const ${name} = React.${name};`).join("\n")}

export default { ...React, ...hooks, ${added.map(({ name }) => name).join(", ")} };
`;

const outputs = [
  [resolve(root, "types/react.d.ts"), dts],
  [resolve(root, "src/react.ts"), runtime],
];

if (process.argv.includes("--check")) {
  const stale = outputs.filter(([file, content]) => {
    try {
      return readFileSync(file, "utf8") !== content;
    } catch {
      return true;
    }
  });
  if (stale.length > 0) {
    console.error(`Stale generated files:\n${stale.map(([file]) => `  ${file}`).join("\n")}`);
    console.error("React or @types/react changed. Run `pnpm generate`, then review the diff and src/hooks.ts.");
    process.exit(1);
  }
  console.log("Generated files are up to date.");
} else {
  for (const [file, content] of outputs) writeFileSync(file, content);
  console.log(
    `Generated shim: ${typeNames.length} type names, ${runtimeNames.length} runtime names, ${overrides.length} redefined.`,
  );
}
if (untyped.length > 0) console.log(`Note: exported by react but not declared in @types/react: ${untyped.join(", ")}`);
